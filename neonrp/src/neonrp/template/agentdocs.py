"""Specs inside the folders an agent works in (「在里面添加就好,不要在外面读 —— spec 也是要给 Claude 和
Codex 其他 agent 读的」).

Claude Code reads ``CLAUDE.md``, Codex and most others ``AGENTS.md``; both read files next to them. So every folder a
creator (or their agent) edits carries:

    AGENTS.md            what this folder is, what may be edited, how to check it, which spec file says what
    CLAUDE.md            the same text
    spec/<name>.md       the specs, copied in (written ones from documents/spec, generated ones from the code)

    template folder      <id>.template/           template · world · soul · contract · ops (its pack) · authoring
    template store       NEONRP_TEMPLATE_WRITE_DIR/   (an index: how templates are laid out, where specs are)
    character library    ~/.worldlines/souls/     soul · template (the cast rows) · contract (the soul protocol)

They are refreshed when a template is forked or imported and by ``neonrp spec sync``; the built-in templates in
``worldlines/templates`` carry them too (a test keeps them current). A run never gets them: build copies only the world.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

MARK = "<!-- generated by neonrp (neonrp spec sync) — edits here are overwritten -->"
LANG = "en"  # agents read English best; the zh specs sit beside them as spec/<name>.zh.md


def _spec_files(names: list[str], *, pack: str | None) -> dict[str, str]:
    from neonrp import spec

    out: dict[str, str] = {}
    for n in names:
        if n in spec.WRITTEN:
            out[f"spec/{n}.md"] = spec.read(n, lang="en")
            try:
                zh = spec.read(n, lang="zh")
                if zh != out[f"spec/{n}.md"]:
                    out[f"spec/{n}.zh.md"] = zh
            except KeyError:
                pass
        else:
            try:
                out[f"spec/{n}.md"] = spec.read(n, pack=pack if n == "ops" else None)
            except Exception:  # noqa: BLE001 — a composed pack (rpg+economy): fall back to its base
                out[f"spec/{n}.md"] = spec.read(n, pack=(pack or "rpg").split("+")[0] if n == "ops" else None)
    return out


def _template_body(t: Any) -> str:
    card = t.data.get("card") or {}
    title = card.get("title") or t.id
    title = title.get("en") or next(iter(title.values()), t.id) if isinstance(title, dict) else title
    contract = t.data.get("play_contract") or "none declared"
    return f"""{MARK}
# {t.id}.template — {title}

A WorldLines **template**: one world, its cast, a play pack (`{t.pack_name}`), a play contract (`{contract}`) and an
orchestration graph. It is the unit that is played, exported and published.

## Before you write

Read the spec for the part you are about to change — they are in `spec/` next to this file:

| You are changing | Read |
|---|---|
| `template.json` (card, mode, cast `souls`, plots, slots, contract, orchestration) | `spec/template.md` |
| anything under `world/` (map, places, NPCs, items, opening) | `spec/world.md` |
| a character (`world/souls/…`, `prompts/souls/<sid>/`) | `spec/soul.md` |
| the experience it promises (`play_contract`) | `spec/contract.md` |
| what the model may write each turn (ops, classes, variables, triggers) | `spec/ops.md` |
| the authoring ops the engine applies for you | `spec/authoring.md` |

Chinese versions: `spec/<name>.zh.md`.

## Rules

- Characters from the library are **links** (`{{"lib": "<name>"}}` in `souls`): do not copy a library soul into this folder;
  what differs in this world goes in `prompts/souls/<sid>/` (only `soul.md`, `persona/`, `rules/`, `agents/`) or `world-overlay/`.
- Do not hard-code world words (a place, a status, a faction) into engine code; they belong in this folder's data.
- `spec/`, `AGENTS.md` and `CLAUDE.md` are generated — edit the specs at their source, not here.

## Check your work

```
neonrp template lint .                  # run in this folder · 0 block = playable and publishable
neonrp template build . /tmp/try-{t.id}   # a run you can open
```
"""


def _store_body(root: Path) -> str:
    return f"""{MARK}
# WorldLines template store

Each `<id>.template/` here is one template (a world + its cast + a play pack + a play contract). Every template folder
has its own `AGENTS.md` and `spec/` — open the template you are working on and read those first.

- New template: copy one (`neonrp template fork <id> <new-id>`), never edit the built-ins in place.
- Bring one in / take one out: `neonrp template import <zip>` · `neonrp template export <id>`.
- Specs for everything: `spec/` in this folder (template · world · soul · contract · authoring).
"""


def _library_body(root: Path) -> str:
    return f"""{MARK}
# WorldLines character library

Each folder here is one character (a soul): identity, personality, rules, memories, sheets, portrait. A character
belongs to no world — templates **link** it (`{{"lib": "<folder name>"}}` in a template's `souls`) and a run copies it
in when the run starts.

- The folder layout and every file: `spec/soul.md`.
- How templates cast a character (the `souls` rows, roles, per-world overrides): `spec/template.md` §3.6.
- What a kind of game asks of a character (sheets per contract, what comes back after a run): `spec/contract.md` §6.
- Do not put world-specific facts into a character here — they go in the template that links it.
- Take one out / bring one back: `neonrp template export --soul <name>` · `neonrp template import <zip>`.
"""


def _write(root: Path, files: dict[str, str]) -> list[str]:
    written: list[str] = []
    for rel, text in files.items():
        p = root / rel
        if p.is_file() and p.read_text(encoding="utf-8") == text:
            continue
        if rel in ("AGENTS.md", "CLAUDE.md") and p.is_file() and MARK not in p.read_text(encoding="utf-8"):
            continue  # the creator's own AGENTS.md / CLAUDE.md is never overwritten
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
        written.append(rel)
    return written


def files_for_template(t: Any) -> dict[str, str]:
    body = _template_body(t)
    return {"AGENTS.md": body, "CLAUDE.md": body,
            **_spec_files(["template", "world", "soul", "contract", "ops", "authoring"], pack=t.pack_name)}


def write_template(t: Any) -> list[str]:
    return _write(t.dir, files_for_template(t))


def write_store(root: Path) -> list[str]:
    body = _store_body(root)
    return _write(root, {"AGENTS.md": body, "CLAUDE.md": body, **_spec_files(["template", "world", "soul", "contract", "authoring"], pack=None)})


def write_library(root: Path) -> list[str]:
    body = _library_body(root)
    return _write(root, {"AGENTS.md": body, "CLAUDE.md": body, **_spec_files(["soul", "template", "contract"], pack=None)})


def sync(*, templates: list[Path] | None = None) -> dict[str, list[str]]:
    """Refresh every folder an agent edits: each writable template, the store root, the character library."""
    from neonrp import template as TP
    from neonrp.core import souls as _souls
    from neonrp.template.author import write_root

    out: dict[str, list[str]] = {}
    dirs = templates if templates is not None else [d for d in TP.discover().values()]
    for d in dirs:
        try:
            t = TP.load(d)
        except TP.TemplateError:
            continue
        out[str(t.dir)] = write_template(t)
    if templates is not None:
        return out  # only the folders asked for
    root = write_root()
    if root is not None and root.is_dir():
        out[str(root)] = write_store(root)
    if _souls.SOUL_HOME.is_dir():
        out[str(_souls.SOUL_HOME)] = write_library(_souls.SOUL_HOME)
    return out
